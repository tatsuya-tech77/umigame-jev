def suggestions(p: dict) -> list[str]:
    """問題ごとの候補2つごとに、共通の候補を1つ混ぜた並び。"""
    own, generic, out = list(p["suggest"]), list(GENERIC_SUGGEST), []
    while own or generic:
        out += own[:2]
        own = own[2:]
        if generic:
            out.append(generic.pop(0))
    return out


def choice_id(pid: str, text: str) -> str:
    """解答の候補の ID。中身から作るので、ID だけ見ても正解はわからない。"""
    import hashlib
    return hashlib.sha256(f"{pid}|{text}".encode()).hexdigest()[:10]


def choice_list(p: dict) -> list[dict]:
    """解答の候補（ID と文）。並び順は ID 順にして、正解の位置を固定しない。"""
    c = p.get("choices")
    if not c:
        return []
    texts = [c["correct"], *c["wrong"]]
    return sorted(({"id": choice_id(p["id"], t), "text": t} for t in texts), key=lambda x: x["id"])


def is_correct_choice(p: dict, cid: str) -> bool:
    c = p.get("choices")
    return bool(c) and cid == choice_id(p["id"], c["correct"])


def get(pid: str) -> dict:
    for p in PUZZLES:
        if p["id"] == pid:
            return p
    raise KeyError(pid)
